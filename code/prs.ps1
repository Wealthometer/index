# Generate random branch name
function Get-RandomBranchName {
    $adjectives = @("feature", "bugfix", "hotfix", "release", "chore", "refactor", "update", "enhance")
    $nouns = @("module", "component", "handler", "service", "utils", "config", "api", "ui", "database", "cache")
    $verbs = @("fix", "add", "remove", "update", "implement", "optimize", "rework", "migrate")
    
    $adj = Get-Random $adjectives
    $noun = Get-Random $nouns
    $verb = Get-Random $verbs
    $id = Get-Random -Minimum 1000 -Maximum 9999
    
    return "$adj/$verb-$noun-$id"
}

# Generate random content
function Get-RandomContent {
    $contentTypes = @("code", "text", "json", "markdown", "yaml")
    $type = Get-Random $contentTypes
    
    switch ($type) {
        "code" {
            $funcName = "func_$(-join ((97..122) | Get-Random -Count 8 | ForEach-Object {[char]$_}))"
            return @"
// Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
// Branch: $(git branch --show-current 2>$null)

function $funcName() {
    const data = {
        id: $((Get-Random -Maximum 9999)),
        timestamp: Date.now(),
        value: $((Get-Random -Maximum 100))
    };
    
    console.log('Processing:', data);
    return data.value * $((Get-Random -Maximum 10));
}

module.exports = { $funcName };
"@
        }
        "text" {
            $lines = @()
            $lineCount = Get-Random -Minimum 5 -Maximum 15
            for ($i = 0; $i -lt $lineCount; $i++) {
                $randomWord = -join ((97..122) | Get-Random -Count (Get-Random -Minimum 5 -Maximum 12) | ForEach-Object {[char]$_})
                $lines += "[$i] Log entry: $randomWord - Status: $(Get-Random @('OK', 'PENDING', 'COMPLETE', 'SKIPPED'))"
            }
            return ($lines -join "`n")
        }
        "json" {
            return @"
{
    "metadata": {
        "generated": "$(Get-Date -Format 'yyyy-MM-ddTHH:mm:ss')",
        "branch": "$(git branch --show-current 2>$null)",
        "version": "1.$((Get-Random -Maximum 100)).$((Get-Random -Maximum 10))"
    },
    "data": {
        "id": $((Get-Random -Maximum 10000)),
        "type": "$(Get-Random @('user', 'system', 'event', 'metric'))",
        "payload": "$(-join ((65..90) + (97..122) | Get-Random -Count 32 | ForEach-Object {[char]$_}))",
        "priority": $(Get-Random -Maximum 5)
    }
}
"@
        }
        "markdown" {
            return @"
# $(Get-Random @('Documentation', 'Changelog', 'Notes', 'Report')) - $(Get-Date -Format 'yyyy-MM-dd')

## Overview
Generated automatically for branch: \`$(git branch --show-current 2>$null)\`

## Details
- **ID**: $((Get-Random -Maximum 10000))
- **Status**: $(Get-Random @('Active', 'Draft', 'Review', 'Complete'))
- **Priority**: $(Get-Random -Maximum 5)/5

## Changes
$((1..(Get-Random -Minimum 2 -Maximum 6) | ForEach-Object { "- Item $_: $(-join ((97..122) | Get-Random -Count 8 | ForEach-Object {[char]$_}))" } | Join-String -Separator "`n"))

---
*Auto-generated by workflow script*
"@
        }
        "yaml" {
            return @"
