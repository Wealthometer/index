# Create a new branch and switch to it
function New-FeatureBranch {
    $branchName = Get-RandomBranchName
    
    Write-Host "`n=== Creating New Branch ===" -ForegroundColor Cyan
    Write-Host "Branch name: $branchName" -ForegroundColor White
    
    # Fetch latest from main
    git fetch origin main 2>$null | Out-Null
    
    # Create and checkout new branch from main
    git checkout -b $branchName origin/main 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Created and switched to branch: $branchName" -ForegroundColor Green
        return $branchName
    } else {
        Write-Host "✗ Failed to create branch" -ForegroundColor Red
        return $null
    }
}

# Create file and commit
function New-Commit {
    param([string]$BranchName)
    
    $timestamp = Get-Date -Format "yyyyMMdd-HHmmss"
    $extension = Get-Random @(".txt", ".js", ".json", ".md", ".yml", ".log")
    $fileName = "auto-$timestamp$extension"
    
    Write-Host "`n=== Creating File ===" -ForegroundColor Cyan
    Write-Host "File: $fileName" -ForegroundColor White
    
    # Generate and write content
    $content = Get-RandomContent
    $content | Set-Content $fileName -Encoding UTF8
    
    # Git add and commit
    git add $fileName | Out-Null
    
    $msg = "$commitMessage [$BranchName] - $timestamp"
    git commit -m $msg 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Committed: $msg" -ForegroundColor Green
        return $fileName
    } else {
        Write-Host "✗ Commit failed" -ForegroundColor Red
        return $null
    }
}

# Push branch and create PR
function New-PullRequest {
    param([string]$BranchName)
    
    Write-Host "`n=== Pushing Branch ===" -ForegroundColor Cyan
    
    git push -u origin $BranchName 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Pushed branch: $branchName" -ForegroundColor Green
        
        # Create PR using gh CLI
        Write-Host "`n=== Creating Pull Request ===" -ForegroundColor Cyan
        
        $prTitle = "Auto PR: $BranchName - $(Get-Date -Format 'yyyy-MM-dd HH:mm')"
        $prBody = "This pull request was automatically generated.`n`n**Branch**: $BranchName`n**Created**: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')`n`nPlease review and merge."
        
        $prUrl = gh pr create --title $prTitle --body $prBody --base main --head $BranchName 2>&1
        
        if ($LASTEXITCODE -eq 0) {
            Write-Host "✓ Created PR: $prUrl" -ForegroundColor Green
            return $prUrl
        } else {
            Write-Host "✗ PR creation failed (may already exist)" -ForegroundColor Yellow
            return $null
        }
    } else {
        Write-Host "✗ Push failed" -ForegroundColor Red
        return $null
    }
}

# Create GitHub issue
function New-GitHubIssue {
    param([string]$BranchName)
    
    Write-Host "`n=== Creating GitHub Issue ===" -ForegroundColor Cyan
    
    $issue = Get-RandomIssue
    
    # Create issue with label
    $label = switch ($issue.Type) {
        "Bug" { "bug" }
        "Feature" { "enhancement" }
        "Task" { "task" }
        "Refactor" { "refactor" }
        "Documentation" { "documentation" }
        "Test" { "testing" }
        default { "automated" }
    }
    
    $issueUrl = gh issue create --title $issue.Title --body $issue.Body --label $label 2>&1
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Created issue: $($issue.Title)" -ForegroundColor Green
        Write-Host "  URL: $issueUrl" -ForegroundColor Gray
        
        # Extract issue number from URL
        $issueNumber = $issueUrl.Split('/')[-1]
        
        return @{
            Number = $issueNumber
            Url = $issueUrl
            Title = $issue.Title
        }
    } else {
        Write-Host "✗ Issue creation failed" -ForegroundColor Red
        return $null
    }
}

# Close the issue
function Close-GitHubIssue {
    param([string]$IssueNumber)
    
    Write-Host "`n=== Closing Issue #$IssueNumber ===" -ForegroundColor Cyan
    
    gh issue close $IssueNumber --comment "Resolved in automated workflow. Closing as complete." 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Closed issue #$IssueNumber" -ForegroundColor Green
        return $true
    } else {
        Write-Host "✗ Failed to close issue" -ForegroundColor Red
        return $false
    }
}

# Create follow-up commit referencing the issue
function New-FollowUpCommit {
    param(
        [string]$BranchName,
        [string]$IssueNumber
    )
    
    Write-Host "`n=== Creating Follow-up Commit ===" -ForegroundColor Cyan
    
    $timestamp = Get-Date -Format "yyyyMMdd-HHmmss"
    $fileName = "fix-$IssueNumber-$timestamp.md"
    
    $content = @"
# Fix for Issue #$IssueNumber

**Status**: Resolved  
**Branch**: $BranchName  
**Timestamp**: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')

## Resolution
This file documents the resolution of issue #$IssueNumber.

## Changes Made
- Applied automated fix
- Updated related components
- Verified functionality

---
*Auto-generated resolution document*
"@
    
    $content | Set-Content $fileName -Encoding UTF8
    git add $fileName | Out-Null
    
    $msg = "Fix #$IssueNumber - Resolution commit [$BranchName]"
    git commit -m $msg 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Created follow-up commit: $msg" -ForegroundColor Green
        
        # Push the new commit
        git push origin $BranchName 2>&1 | Out-Null
        Write-Host "✓ Pushed follow-up commit" -ForegroundColor Green
        
        return $fileName
    } else {
        Write-Host "✗ Follow-up commit failed" -ForegroundColor Red
        return $null
    }
}

# Merge the PR (optional - uncomment if you want auto-merge)
function Merge-PullRequest {
    param([string]$BranchName)
    
    Write-Host "`n=== Merging Pull Request ===" -ForegroundColor Cyan
    
    gh pr merge $BranchName --squash --delete-branch --subject "Auto-merge: $BranchName" 2>&1 | Out-Null
    
    if ($LASTEXITCODE -eq 0) {
        Write-Host "✓ Merged and deleted branch: $BranchName" -ForegroundColor Green
        return $true
    } else {
        Write-Host "✗ Merge failed (may require manual review)" -ForegroundColor Yellow
        return $false
    }
}

# Main workflow
function Start-Workflow {
    $iteration = 0
    
    while ($true) {
        $iteration++
        Write-Host "`n========================================" -ForegroundColor Magenta
        Write-Host "  WORKFLOW ITERATION #$iteration" -ForegroundColor Magenta
        Write-Host "  $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')" -ForegroundColor Magenta
        Write-Host "========================================" -ForegroundColor Magenta
        
        try {
            # Step 1: Create new branch
            $branch = New-FeatureBranch
            if (-not $branch) { throw "Branch creation failed" }
            
            # Step 2: Create initial commit
            $file1 = New-Commit -BranchName $branch
            if (-not $file1) { throw "Initial commit failed" }
            
            # Step 3: Push and create PR
            $prUrl = New-PullRequest -BranchName $branch
            
            # Step 4: Create GitHub issue
            $issue = New-GitHubIssue -BranchName $branch
            if (-not $issue) { throw "Issue creation failed" }
            
            # Step 5: Close the issue
            $closed = Close-GitHubIssue -IssueNumber $issue.Number
            
            # Step 6: Create follow-up commit referencing the issue
            $file2 = New-FollowUpCommit -BranchName $branch -IssueNumber $issue.Number
            
            # Step 7: Optional - merge the PR
            # Uncomment the next line to enable auto-merge
            # $merged = Merge-PullRequest -BranchName $branch
            
            # Return to main branch for next iteration
            git checkout main 2>&1 | Out-Null
            
            Write-Host "`n========================================" -ForegroundColor Green
            Write-Host "  WORKFLOW COMPLETE ✓" -ForegroundColor Green
            Write-Host "  Branch: $branch" -ForegroundColor Green
            Write-Host "  Issue: #$($issue.Number)" -ForegroundColor Green
            Write-Host "========================================" -ForegroundColor Green
            
        } catch {
            Write-Host "`n========================================" -ForegroundColor Red
            Write-Host "  WORKFLOW ERROR ✗" -ForegroundColor Red
            Write-Host "  $($_.Exception.Message)" -ForegroundColor Red
            Write-Host "========================================" -ForegroundColor Red
            
            # Return to main branch on error
            git checkout main 2>&1 | Out-Null
        }
        
        # Wait before next iteration
        Write-Host "`nWaiting $delaySeconds seconds before next iteration..." -ForegroundColor Blue
        Start-Sleep -Seconds $delaySeconds
    }
}

